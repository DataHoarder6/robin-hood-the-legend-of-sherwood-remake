#!/usr/bin/env bash
# Two generated notes, one authority each:
#
#   scripts/release-notes.sh <summary.json> <version>
#     Generate docs/releases/<version>.md from a release gate's summary.json.
#   scripts/release-notes.sh whats-new [--repo DIR] [--source FILE] [--out FILE]
#     Generate docs/RELEASE_NOTES.md from docs/releases/whats-new.json, the
#     annotated tags and docs/NEW_FEATURES.md. Every quoted line is checked
#     against those sources; a missing reference fails instead of inventing one.
#
# The summary is authoritative: every quoted value comes from that file, so a
# note cannot drift from the gate that produced it. release-gate.sh decides
# whether a run was clean; this script only formats the verdict it was given.
# Regeneration overwrites the note.
set -euo pipefail

exec </dev/null

repository=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd -- "$repository"

usage() {
    awk 'NR > 1 && /^[^#]/{exit} NR > 1{sub(/^# ?/, ""); print}' "${BASH_SOURCE[0]}" >&2
    exit 2
}
case "${1:-}" in -h | --help) usage ;; esac

# whats-new: a manifest of tag -> NEW_FEATURES.md labels and commit SHAs. Both
# are verified against the tag's own history, so the output quotes only sources
# that exist in that release. Regenerating from the same inputs is byte-stable.
if [[ ${1:-} == whats-new ]]; then
    shift
    repo=$repository
    source=docs/releases/whats-new.json
    out=docs/RELEASE_NOTES.md
    while (( $# )); do
        case "$1" in
            --repo) repo=${2:?--repo needs a directory}; shift 2 ;;
            --source) source=${2:?--source needs a file}; shift 2 ;;
            --out) out=${2:?--out needs a file}; shift 2 ;;
            *)
                printf 'release-notes: unknown whats-new option %s\n' "$1" >&2
                exit 2
                ;;
        esac
    done
    [[ -f $source ]] || {
        printf 'release-notes: no whats-new manifest at %s\n' "$source" >&2
        exit 2
    }
    python3 -B - "$repo" "$source" "$out" <<'PY'
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

repo, source_path, out_path = (Path(value).resolve() for value in sys.argv[1:4])


def fail(message):
    print(f"release-notes: {message}", file=sys.stderr)
    raise SystemExit(2)


def git(*args):
    result = subprocess.run(["git", "-C", str(repo), *args], text=True, capture_output=True)
    if result.returncode != 0:
        fail(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def ancestor(commit, ref):
    return subprocess.run(
        ["git", "-C", str(repo), "merge-base", "--is-ancestor", commit, ref]
    ).returncode == 0


def feature_bullets(text):
    """Full bullet blocks from NEW_FEATURES.md, keyed by their bold label."""
    bullets = {}
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        match = re.match(r"^- \*\*(.+?)\*\*", line)
        if not match:
            index += 1
            continue
        label = match.group(1)
        block = [line]
        index += 1
        while index < len(lines) and lines[index].strip() and not lines[index].startswith(("- ", "#")):
            block.append(lines[index])
            index += 1
        bullets[label] = block
    return bullets


try:
    manifest = json.loads(source_path.read_text(encoding="utf-8"))
except (OSError, json.JSONDecodeError) as error:
    fail(f"cannot read {source_path}: {error}")
if not isinstance(manifest, dict) or not manifest:
    fail("whats-new manifest must be a non-empty object keyed by tag")
for tag, entry in manifest.items():
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        fail(f"invalid tag {tag!r}")
    if not isinstance(entry, dict) or any(
        key not in ("new_features", "commits") for key in entry
    ):
        fail(f"{tag}: manifest entry must hold only new_features and commits")
    for key in ("new_features", "commits"):
        if key in entry and (not isinstance(entry[key], list) or not all(
            isinstance(value, str) for value in entry[key]
        )):
            fail(f"{tag}: {key} must be a list of strings")
    if not entry.get("new_features") and not entry.get("commits"):
        fail(f"{tag}: names no sources")

tags = sorted(manifest, key=lambda tag: tuple(int(part) for part in tag[1:].split(".")))
lines = [
    "# What's new by release",
    "",
    "Generated by [`scripts/release-notes.sh`](../scripts/release-notes.sh) `whats-new`",
    "from [whats-new.json](releases/whats-new.json), the annotated tags and",
    "[NEW_FEATURES.md](NEW_FEATURES.md). Each bullet and commit is quoted from the",
    "release's own history; nothing is inferred. The native release publisher pastes",
    "the matching tag section into the GitHub release body. Do not hand-edit this file.",
    "[RELEASES.md](RELEASES.md) owns the process; [releases/](releases/) holds the",
    "gate evidence for a candidate.",
]

previous = None
for tag in tags:
    tag_commit = git("rev-parse", "--verify", f"refs/tags/{tag}^{{commit}}")
    announcement = git("for-each-ref", "--format=%(contents:subject)", f"refs/tags/{tag}")
    if not announcement:
        fail(f"{tag} has no tag annotation to quote")
    bullets = feature_bullets(
        subprocess.check_output(
            ["git", "-C", str(repo), "show", f"{tag}:docs/NEW_FEATURES.md"], text=True
        )
    )
    lines += ["", f"## {tag}", "", f"Tag summary: {announcement}", "", "### What's new", ""]
    for label in manifest[tag].get("new_features", []):
        if label not in bullets:
            fail(f"{tag}: {label!r} is not a bullet in NEW_FEATURES.md at {tag}")
        lines += bullets[label]
    commits = manifest[tag].get("commits", [])
    if commits:
        lines += ["", "### Source commits", ""]
    for short in commits:
        full = git("rev-parse", "--verify", f"{short}^{{commit}}")
        if not full.startswith(short):
            fail(f"{tag}: {short} does not name commit {full}")
        if not ancestor(full, tag_commit) or (previous and ancestor(full, previous)):
            fail(f"{tag}: {short} is outside {previous or 'root'}..{tag}")
        subject = git("show", "-s", "--format=%s", full)
        lines.append(f"- `{full[:9]}` {subject}")
    previous = tag

out_path.parent.mkdir(parents=True, exist_ok=True)
handle = tempfile.NamedTemporaryFile(
    "w", encoding="utf-8", dir=out_path.parent, prefix=".release-notes-", delete=False
)
try:
    with handle:
        handle.write("\n".join(lines).rstrip() + "\n")
    os.replace(handle.name, out_path)
except BaseException:
    os.unlink(handle.name)
    raise
print(f"release-notes: wrote {out_path}")
PY
    exit $?
fi

if (( $# != 2 )); then
    printf 'usage: scripts/release-notes.sh <summary.json> <version>\n' >&2
    exit 2
fi

summary=$1
version=$2

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
    printf 'release-notes: version must be X.Y.Z, got %s\n' "$version" >&2
    exit 2
}
[[ -f $summary ]] || {
    printf 'release-notes: no summary.json at %s\n' "$summary" >&2
    exit 2
}

mkdir -p -- docs/releases
out="docs/releases/$version.md"
tmp=$(mktemp "${TMPDIR:-/tmp}/robin-release-notes.XXXXXX")
trap 'rm -f -- "$tmp"' EXIT

python3 -B - "$summary" "$version" >"$tmp" <<'PY'
import json
import sys

summary_path, version = sys.argv[1], sys.argv[2]
with open(summary_path, encoding="utf-8") as handle:
    data = json.load(handle)

verdict = data["verdict"]
h23 = data["verdicts"]["H23"]
rows = data["selected"]
row_list = ", ".join(f"`{row}`" for row in rows)
verdict_pairs = ", ".join(f"{row}={data['verdicts'][row]}" for row in rows)
count = len(rows)

print(f"""# {version} release evidence

Generated by `scripts/release-notes.sh` from the gate's `summary.json`. Every
quoted value below comes from that file; [`release-gate.sh`](../../scripts/release-gate.sh)
is the authority that the run was clean. This note is one release's evidence,
not the process — [`RELEASES.md`](../RELEASES.md) owns that, and
[`DEFECTS.md`](../DEFECTS.md) owns D06's status.

## Candidate

- Snapshot (`.snapshot`): `{data['snapshot']}`
- Binary SHA-256 (`.binary_sha256`): `{data['binary_sha256']}`

## Gate counts

| Field | Value from summary.json |
| --- | --- |
| `.suite` | `{data['suite']}` |
| `.layer` | `{data['layer']}` |
| `.verdict` | `{verdict}` |
| process rows in `.selected` | {count} |
| `.refused` entries | {len(data['refused'])} |
| `.harness_gaps` entries | {len(data['harness_gaps'])} |
| `.elapsed_s` | `{data['elapsed_s']}` |

The {count} rows in `.selected`: {row_list}.

## H23 evidence

- `.verdicts.H23`: `{h23}`
- `.verdicts` for the selected rows: {verdict_pairs}
- `.scenarios.H23.evidence`: `{data['scenarios']['H23']['evidence']}`

## Still human

The two-seat `robin --version` comparison on every seat (RELEASES.md step 5,
[PLAY.md](../PLAY.md)) remains an explicit opt-out for runners and still needs
the owner. A tag is not announced until that check and the gate above pass.
""", end="")
PY

mv -- "$tmp" "$out"
printf 'release-notes: wrote %s\n' "$out"

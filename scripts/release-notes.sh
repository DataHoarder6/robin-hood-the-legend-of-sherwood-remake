#!/usr/bin/env bash
# Generate docs/releases/<version>.md from a release gate's summary.json.
#
#   scripts/release-notes.sh <summary.json> <version>
#
# The summary is authoritative: every quoted value comes from that file, so a
# note cannot drift from the gate that produced it. release-gate.sh decides
# whether a run was clean; this script only formats the verdict it was given.
# Regeneration overwrites the note.
set -euo pipefail

exec </dev/null

repository=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd -- "$repository"

usage() {
    awk 'NR > 1 && /^[^#]/{exit} NR > 1{sub(/^# ?/, ""); print}' "${BASH_SOURCE[0]}" >&2
    exit 2
}
case "${1:-}" in -h | --help) usage ;; esac
if (( $# != 2 )); then
    printf 'usage: scripts/release-notes.sh <summary.json> <version>\n' >&2
    exit 2
fi

summary=$1
version=$2

[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
    printf 'release-notes: version must be X.Y.Z, got %s\n' "$version" >&2
    exit 2
}
[[ -f $summary ]] || {
    printf 'release-notes: no summary.json at %s\n' "$summary" >&2
    exit 2
}

mkdir -p -- docs/releases
out="docs/releases/$version.md"
tmp=$(mktemp "${TMPDIR:-/tmp}/robin-release-notes.XXXXXX")
trap 'rm -f -- "$tmp"' EXIT

python3 -B - "$summary" "$version" >"$tmp" <<'PY'
import json
import sys

summary_path, version = sys.argv[1], sys.argv[2]
with open(summary_path, encoding="utf-8") as handle:
    data = json.load(handle)

verdict = data["verdict"]
h23 = data["verdicts"]["H23"]
rows = data["selected"]
row_list = ", ".join(f"`{row}`" for row in rows)
verdict_pairs = ", ".join(f"{row}={data['verdicts'][row]}" for row in rows)
count = len(rows)

print(f"""# {version} release evidence

Generated by `scripts/release-notes.sh` from the gate's `summary.json`. Every
quoted value below comes from that file; [`release-gate.sh`](../../scripts/release-gate.sh)
is the authority that the run was clean. This note is one release's evidence,
not the process — [`RELEASES.md`](../RELEASES.md) owns that, and
[`DEFECTS.md`](../DEFECTS.md) owns D06's status.

## Candidate

- Snapshot (`.snapshot`): `{data['snapshot']}`
- Binary SHA-256 (`.binary_sha256`): `{data['binary_sha256']}`

## Gate counts

| Field | Value from summary.json |
| --- | --- |
| `.suite` | `{data['suite']}` |
| `.layer` | `{data['layer']}` |
| `.verdict` | `{verdict}` |
| process rows in `.selected` | {count} |
| `.refused` entries | {len(data['refused'])} |
| `.harness_gaps` entries | {len(data['harness_gaps'])} |
| `.elapsed_s` | `{data['elapsed_s']}` |

The {count} rows in `.selected`: {row_list}.

## H23 evidence

- `.verdicts.H23`: `{h23}`
- `.verdicts` for the selected rows: {verdict_pairs}
- `.scenarios.H23.evidence`: `{data['scenarios']['H23']['evidence']}`

## Still human

The two-seat `robin --version` comparison on every seat (RELEASES.md step 5,
[PLAY.md](../PLAY.md)) remains an explicit opt-out for runners and still needs
the owner. A tag is not announced until that check and the gate above pass.
""", end="")
PY

mv -- "$tmp" "$out"
printf 'release-notes: wrote %s\n' "$out"
